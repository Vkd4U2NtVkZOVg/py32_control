#define NTC_TABLE_COUNT (sizeof(s_ntc_table) / sizeof(s_ntc_table[0]))

int32_t NTC3950_ResistanceToMilliCelsius(uint32_t resistance_ohm)
{
    uint32_t i;
    if (resistance_ohm >= s_ntc_table[0].resistance_ohm) return (int32_t)s_ntc_table[0].celsius * 1000;
    if (resistance_ohm <= s_ntc_table[NTC_TABLE_COUNT - 1U].resistance_ohm) return (int32_t)s_ntc_table[NTC_TABLE_COUNT - 1U].celsius * 1000;
    for (i = 0U; i + 1U < NTC_TABLE_COUNT; i++) {
        uint32_t r_hi = s_ntc_table[i].resistance_ohm;
        uint32_t r_lo = s_ntc_table[i + 1U].resistance_ohm;
        if ((resistance_ohm <= r_hi) && (resistance_ohm >= r_lo)) {
            int32_t t_hi = (int32_t)s_ntc_table[i].celsius * 1000;
            int32_t t_lo = (int32_t)s_ntc_table[i + 1U].celsius * 1000;
            int64_t num = (int64_t)(resistance_ohm - r_lo) * (t_hi - t_lo);
            return t_lo + (int32_t)(num / (int64_t)(r_hi - r_lo));
        }
    }
    return 0;
}

uint32_t NTC3950_AdcToResistance(uint16_t adc_code)
{
    if (adc_code == 0U) return 0xFFFFFFFFUL;
    if (adc_code >= NTC3950_ADC_FULL_SCALE) return 0U;
    return (uint32_t)(((uint64_t)NTC3950_FIXED_RES_OHM *
                       (NTC3950_ADC_FULL_SCALE - adc_code)) / adc_code);
}

int32_t NTC3950_AdcToMilliCelsius(uint16_t adc_code)
{
    return NTC3950_ResistanceToMilliCelsius(NTC3950_AdcToResistance(adc_code));
}
